create or replace function public.jl_ludo_accept_rules(p_token text,p_room uuid,p_accept boolean)
returns jsonb
language plpgsql
security definer
set search_path='public'
as $$
declare
  me uuid:=public.jl_player_id(p_token);
  r public.ludo_rooms%rowtype;
  c int;
  a int;
begin
  select * into r from public.ludo_rooms where id=p_room for update;
  if r.id is null or r.status not in ('waiting','negotiating') or not public.jl_ludo_is_member(p_room,me) then
    raise exception 'Sala indisponível.';
  end if;
  if r.play_mode='free' then perform public.jl_free_access_require(me); end if;

  if not p_accept then
    update public.ludo_room_players set accepted_rules_version=null where room_id=p_room and player_id=me;
    perform public.jl_ludo_event(p_room,me,'rules_declined',jsonb_build_object('version',r.rules_version));
    return public.jl_ludo_room_state(p_token,p_room);
  end if;

  update public.ludo_room_players
  set accepted_rules_version=r.rules_version
  where room_id=p_room and player_id=me and status<>'left';
  perform public.jl_ludo_event(p_room,me,'rules_accepted',jsonb_build_object('version',r.rules_version,'no_deadline',true));

  select count(*),count(*) filter(where accepted_rules_version=r.rules_version)
  into c,a from public.ludo_room_players where room_id=p_room and status<>'left';

  if c=r.player_count and a=c then
    if r.play_mode='free' then
      update public.ludo_room_players set stake_paid=true,stake_amount=0 where room_id=p_room and status<>'left';
      update public.ludo_rooms set status='funding',action_deadline=null,negotiation_grace_used=false,updated_at=now() where id=p_room;
      perform public.jl_ludo_start_game(p_room);
    else
      update public.ludo_rooms
      set status='funding',action_deadline=now()+make_interval(secs=>(rules->>'stake_seconds')::int),
          negotiation_grace_used=false,updated_at=now()
      where id=p_room;
    end if;
    perform public.jl_ludo_event(p_room,me,'rules_unanimous',jsonb_build_object('version',r.rules_version,'free',r.play_mode='free'));
  end if;
  return public.jl_ludo_room_state(p_token,p_room);
end;
$$;

create or replace function public.jl_dama_accept_settings(p_token text,p_room uuid,p_accept boolean default true)
returns jsonb
language plpgsql
security definer
set search_path='public'
as $$
declare
  me uuid:=public.jl_player_id(p_token);
  r public.dama_rooms%rowtype;
  rp public.dama_room_players%rowtype;
  firstp uuid;
begin
  select * into r from public.dama_rooms where id=p_room for update;
  select * into rp from public.dama_room_players
  where room_id=p_room and player_id=me and status<>'left' for update;
  if r.id is null or rp.player_id is null or r.status<>'negotiating' then raise exception 'Partida indisponível para aceitação.'; end if;
  if r.play_mode='free' then perform public.jl_free_access_require(me); end if;
  if me=r.host_id then return public.jl_dama_room_state(p_token,p_room); end if;

  if not coalesce(p_accept,true) then
    delete from public.dama_room_players where room_id=p_room and player_id=me;
    update public.dama_rooms set guest_id=null,status='waiting',updated_at=now() where id=p_room;
    perform public.jl_dama_event(p_room,me,'settings_declined','{}'::jsonb);
    return jsonb_build_object('ok',true,'accepted',false);
  end if;

  update public.dama_room_players set settings_accepted=true where room_id=p_room and player_id=me;

  if r.play_mode='free' then
    perform public.jl_free_game_require(r.host_id,'dama');
    perform public.jl_free_game_require(me,'dama');
    update public.dama_room_players set stake_paid=true,stake_amount=0 where room_id=p_room and status<>'left';
    perform public.jl_dama_init_board(p_room);
    firstp:=case r.first_player_choice when 'host' then r.host_id else r.guest_id end;
    update public.dama_rooms
    set status='ready',current_player_id=firstp,started_at=null,action_deadline=null,
        board_version=0,move_seq=0,quiet_king_moves=0,regulation_key=null,
        regulation_moves=0,regulation_limit=0,pot=0,updated_at=now()
    where id=p_room;
    perform public.jl_dama_event(p_room,firstp,'game_ready',jsonb_build_object('first_player',firstp,'timer_starts_after_first_move',true,'free',true));
    insert into public.dama_positions(room_id,position_key,occurrences)
    values(p_room,public.jl_dama_position_key(p_room,firstp),1)
    on conflict(room_id,position_key) do update
    set occurrences=public.dama_positions.occurrences+1,updated_at=now();
  else
    update public.dama_rooms set status='funding',updated_at=now() where id=p_room;
    perform public.jl_dama_event(p_room,me,'settings_accepted',jsonb_build_object(
      'bet_amount',r.bet_amount,'turn_seconds',r.turn_seconds,
      'host_color',r.host_color,'first_player',r.first_player_choice
    ));
  end if;
  return public.jl_dama_room_state(p_token,p_room);
end;
$$;

