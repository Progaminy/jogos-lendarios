create or replace function public.jl_admin_free_access_review(p_token text,p_request_id uuid,p_decision text)
returns jsonb
language plpgsql
security definer
set search_path='pg_catalog','public'
as $$
declare
  req public.free_access_requests%rowtype;
  mem public.free_access_memberships%rowtype;
  admin_id uuid;
  base_until timestamptz;
  next_until timestamptz;
begin
  perform public.jl_require_admin_elevated(p_token);
  admin_id:=public.jl_admin_account_id(p_token);
  if p_decision not in ('approved','rejected') then raise exception 'Decisão inválida.'; end if;

  select * into req from public.free_access_requests where id=p_request_id for update;
  if req.id is null or req.status<>'pending' then raise exception 'Pedido indisponível.'; end if;

  update public.free_access_requests
  set status=p_decision,reviewed_at=now(),reviewed_by=admin_id
  where id=req.id;

  if p_decision='approved' then
    select * into mem from public.free_access_memberships where player_id=req.player_id for update;
    base_until:=greatest(coalesce(mem.valid_until,now()),now());
    next_until:=base_until+make_interval(months=>coalesce(req.months,1));
    if mem.player_id is null then
      insert into public.free_access_memberships(
        player_id,active,amount_paid,request_id,activated_at,updated_at,valid_until
      ) values(req.player_id,true,req.amount,req.id,now(),now(),next_until);
    else
      update public.free_access_memberships
      set active=true,
          amount_paid=round(amount_paid+req.amount,2),
          request_id=req.id,
          valid_until=next_until,
          updated_at=now()
      where player_id=req.player_id;
    end if;
  elsif req.amount>0 then
    perform public.jl_lock_player_wallet(req.player_id);
    update public.players set balance=round(balance+req.amount,2),updated_at=now() where id=req.player_id;
    insert into public.transactions(player_id,kind,amount,status,reference_id,note)
    values(req.player_id,'free_access_refund',req.amount,'completed',req.id,'FREE · pagamento devolvido');
    update public.free_access_requests set refunded_at=now() where id=req.id;
  end if;

  return public.jl_admin_free_access_overview(p_token);
end;
$$;

