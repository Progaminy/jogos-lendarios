create or replace function public.jl_free_room_player_guard()
returns trigger
language plpgsql
security definer
set search_path='pg_catalog','public'
as $$
declare pm text; game_name text;
begin
  if tg_table_name='ludo_room_players' then
    select play_mode into pm from public.ludo_rooms where id=new.room_id;
    game_name:='ludo';
  else
    select play_mode into pm from public.dama_rooms where id=new.room_id;
    game_name:='dama';
  end if;
  if pm='free' then perform public.jl_free_game_require(new.player_id,game_name); end if;
  return new;
end;
$$;

create or replace function public.jl_free_usage_on_room_start()
returns trigger
language plpgsql
security definer
set search_path='pg_catalog','public'
as $$
declare x record; game_name text;
begin
  if new.play_mode<>'free' then return new; end if;
  if tg_table_name='ludo_rooms' then
    if new.status<>'playing' or old.status='playing' then return new; end if;
    game_name:='ludo';
    for x in select player_id from public.ludo_room_players where room_id=new.id and status<>'left' loop
      perform public.jl_free_game_require(x.player_id,game_name);
      if not public.jl_free_access_active(x.player_id) then
        insert into public.free_trial_usage(player_id,game_key,room_id)
        values(x.player_id,game_name,new.id) on conflict do nothing;
      end if;
    end loop;
  elsif tg_table_name='dama_rooms' then
    if new.status<>'ready' or old.status='ready' then return new; end if;
    game_name:='dama';
    for x in select player_id from public.dama_room_players where room_id=new.id and status<>'left' loop
      perform public.jl_free_game_require(x.player_id,game_name);
      if not public.jl_free_access_active(x.player_id) then
        insert into public.free_trial_usage(player_id,game_key,room_id)
        values(x.player_id,game_name,new.id) on conflict do nothing;
      end if;
    end loop;
  end if;
  return new;
end;
$$;

