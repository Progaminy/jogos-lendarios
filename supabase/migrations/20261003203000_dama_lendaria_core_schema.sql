-- Dama Lendária — motor 8x8, 1x1, autoridade no servidor.
-- Base: Damas Brasileiras (64 casas): captura obrigatória, lei da maioria,
-- pedra captura para frente/trás, dama voadora, promoção somente ao terminar o lance.

create table if not exists public.dama_rooms (
  id uuid primary key default extensions.gen_random_uuid(),
  code text not null unique,
  host_id uuid not null references public.players(id) on delete restrict,
  bet_amount numeric(12,2) not null check (bet_amount >= 10 and bet_amount = trunc(bet_amount)),
  turn_seconds integer not null check (turn_seconds in (120,180)),
  host_color text not null check (host_color in ('white','black')),
  host_starts boolean not null default true,
  is_public boolean not null default false,
  status text not null default 'waiting' check (status in ('waiting','funding','ready','playing','finished','cancelled')),
  pot numeric(12,2) not null default 0 check (pot >= 0),
  current_player_id uuid references public.players(id) on delete restrict,
  action_deadline timestamptz,
  started_at timestamptz,
  finished_at timestamptz,
  winner_player_id uuid references public.players(id) on delete restrict,
  result text check (result is null or result in ('win','draw')),
  finish_reason text,
  commission_total numeric(12,2) not null default 0 check (commission_total >= 0),
  move_no integer not null default 0,
  king_only_count integer not null default 0,
  endgame_key text,
  endgame_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.dama_room_players (
  room_id uuid not null references public.dama_rooms(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete restrict,
  seat integer not null check (seat in (1,2)),
  color text not null check (color in ('white','black')),
  stake_paid boolean not null default false,
  stake_amount numeric(12,2) not null default 0,
  status text not null default 'active' check (status in ('active','finished','left','forfeited')),
  joined_at timestamptz not null default now(),
  primary key(room_id,player_id),
  unique(room_id,seat),
  unique(room_id,color)
);

create table if not exists public.dama_pieces (
  id uuid primary key default extensions.gen_random_uuid(),
  room_id uuid not null references public.dama_rooms(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete restrict,
  piece_no integer not null check (piece_no between 1 and 12),
  row_no integer not null check (row_no between 0 and 7),
  col_no integer not null check (col_no between 0 and 7),
  is_king boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(room_id,player_id,piece_no),
  unique(room_id,row_no,col_no)
);

create table if not exists public.dama_events (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.dama_rooms(id) on delete cascade,
  player_id uuid references public.players(id) on delete set null,
  event_type text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.dama_positions (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.dama_rooms(id) on delete cascade,
  position_key text not null,
  player_to_move uuid not null references public.players(id) on delete restrict,
  move_no integer not null,
  created_at timestamptz not null default now()
);

create table if not exists public.dama_payouts (
  id uuid primary key default extensions.gen_random_uuid(),
  room_id uuid not null references public.dama_rooms(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete restrict,
  gross_amount numeric(12,2) not null,
  commission numeric(12,2) not null,
  net_amount numeric(12,2) not null,
  created_at timestamptz not null default now(),
  unique(room_id,player_id)
);

create table if not exists public.dama_invitations (
  id uuid primary key default extensions.gen_random_uuid(),
  room_id uuid not null references public.dama_rooms(id) on delete cascade,
  invited_by uuid not null references public.players(id) on delete cascade,
  target_player_id uuid not null references public.players(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted','declined','cancelled')),
  created_at timestamptz not null default now(),
  responded_at timestamptz
);

create table if not exists public.dama_draw_offers (
  id uuid primary key default extensions.gen_random_uuid(),
  room_id uuid not null references public.dama_rooms(id) on delete cascade,
  proposed_by uuid not null references public.players(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted','declined','cancelled')),
  created_move_no integer not null,
  created_at timestamptz not null default now(),
  responded_at timestamptz
);

create table if not exists public.dama_signals (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.dama_rooms(id) on delete cascade,
  from_player_id uuid not null references public.players(id) on delete cascade,
  to_player_id uuid not null references public.players(id) on delete cascade,
  signal_type text not null check (signal_type in ('offer','answer','ice','renegotiate')),
  payload jsonb not null,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now()+interval '2 minutes')
);

create index if not exists dama_rooms_active_idx on public.dama_rooms(status,created_at desc);
create index if not exists dama_rooms_deadline_idx on public.dama_rooms(action_deadline) where status='playing';
create index if not exists dama_players_player_idx on public.dama_room_players(player_id,room_id);
create index if not exists dama_events_room_idx on public.dama_events(room_id,id desc);
create index if not exists dama_positions_room_key_idx on public.dama_positions(room_id,position_key,player_to_move);
create index if not exists dama_invites_target_idx on public.dama_invitations(target_player_id,status,created_at desc);
create index if not exists dama_signals_target_idx on public.dama_signals(to_player_id,room_id,id);

