
create extension if not exists pg_net with schema extensions;

create table if not exists public.player_notifications (
  id bigint generated by default as identity primary key,
  player_id uuid not null references public.players(id) on delete cascade,
  kind text not null default 'info',
  title text not null,
  message text not null default '',
  href text not null default '',
  source_key text,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  dismissed_at timestamptz,
  push_attempted_at timestamptz,
  push_sent_at timestamptz
);

create unique index if not exists player_notifications_source_uidx
  on public.player_notifications(player_id, source_key)
  where source_key is not null;

create index if not exists player_notifications_player_created_idx
  on public.player_notifications(player_id, created_at desc)
  where dismissed_at is null;

alter table public.player_notifications enable row level security;
revoke all on table public.player_notifications from anon, authenticated;

create table if not exists public.player_follows (
  follower_id uuid not null references public.players(id) on delete cascade,
  followed_id uuid not null references public.players(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (follower_id, followed_id),
  constraint player_follows_not_self check (follower_id <> followed_id)
);

create index if not exists player_follows_followed_idx
  on public.player_follows(followed_id, created_at desc);

alter table public.player_follows enable row level security;
revoke all on table public.player_follows from anon, authenticated;

create table if not exists public.player_push_subscriptions (
  id uuid primary key default extensions.gen_random_uuid(),
  player_id uuid not null references public.players(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  user_agent text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_success_at timestamptz,
  disabled_at timestamptz
);

create index if not exists player_push_subscriptions_player_idx
  on public.player_push_subscriptions(player_id)
  where disabled_at is null;

alter table public.player_push_subscriptions enable row level security;
revoke all on table public.player_push_subscriptions from anon, authenticated;

create index if not exists player_sessions_player_seen_idx
  on public.player_sessions(player_id, last_seen_at desc);

create or replace function public.jl_notification_create(
  p_player_id uuid,
  p_kind text,
  p_title text,
  p_message text default '',
  p_href text default '',
  p_source_key text default null
)
returns bigint
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  v_id bigint;
  v_source text := nullif(trim(coalesce(p_source_key,'')),'');
begin
  if p_player_id is null or not exists(
    select 1 from public.players p
    where p.id=p_player_id and not p.blocked and p.deleted_at is null
  ) then
    return null;
  end if;

  if v_source is null then
    insert into public.player_notifications(player_id,kind,title,message,href)
    values(
      p_player_id,
      left(coalesce(nullif(trim(p_kind),''),'info'),60),
      left(coalesce(nullif(trim(p_title),''),'Notificação'),160),
      left(coalesce(p_message,''),700),
      left(coalesce(p_href,''),500)
    )
    returning id into v_id;
  else
    insert into public.player_notifications(player_id,kind,title,message,href,source_key)
    values(
      p_player_id,
      left(coalesce(nullif(trim(p_kind),''),'info'),60),
      left(coalesce(nullif(trim(p_title),''),'Notificação'),160),
      left(coalesce(p_message,''),700),
      left(coalesce(p_href,''),500),
      left(v_source,220)
    )
    on conflict (player_id, source_key) where source_key is not null
    do update set
      kind=excluded.kind,
      title=excluded.title,
      message=excluded.message,
      href=excluded.href
    returning id into v_id;
  end if;

  return v_id;
end;
$$;

revoke all on function public.jl_notification_create(uuid,text,text,text,text,text) from public, anon, authenticated;
grant execute on function public.jl_notification_create(uuid,text,text,text,text,text) to service_role;

create or replace function public.jl_notifications_feed(
  p_token text,
  p_limit integer default 80
)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  me uuid := public.jl_player_id(p_token);
  lim integer := greatest(1,least(coalesce(p_limit,80),100));
  rows jsonb;
begin
  update public.player_sessions
  set last_seen_at=now()
  where token_hash=public.jl_token_hash(p_token)
    and expires_at>now();

  select coalesce(jsonb_agg(x order by x.created_at desc),'[]'::jsonb)
  into rows
  from (
    select
      coalesce(n.source_key,'server:'||n.id::text) as id,
      n.id as "serverId",
      n.kind as type,
      n.title,
      n.message,
      n.href,
      n.created_at as "createdAt",
      (n.read_at is not null) as read,
      true as "serverBacked"
    from public.player_notifications n
    where n.player_id=me
      and n.dismissed_at is null
    order by n.created_at desc
    limit lim
  ) x;

  return rows;
end;
$$;

create or replace function public.jl_notifications_mark_read(
  p_token text,
  p_notification_id bigint default null,
  p_source_key text default null,
  p_all boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  me uuid := public.jl_player_id(p_token);
  changed integer := 0;
begin
  if coalesce(p_all,false) then
    update public.player_notifications
    set read_at=coalesce(read_at,now())
    where player_id=me and dismissed_at is null and read_at is null;
    get diagnostics changed=row_count;
  elsif p_notification_id is not null then
    update public.player_notifications
    set read_at=coalesce(read_at,now())
    where player_id=me and id=p_notification_id and dismissed_at is null;
    get diagnostics changed=row_count;
  elsif nullif(trim(coalesce(p_source_key,'')),'') is not null then
    update public.player_notifications
    set read_at=coalesce(read_at,now())
    where player_id=me and source_key=p_source_key and dismissed_at is null;
    get diagnostics changed=row_count;
  end if;
  return jsonb_build_object('ok',true,'changed',changed);
end;
$$;

