grant execute on function public.jl_social_follow(text,uuid,boolean) to anon, authenticated;

create or replace function public.jl_push_subscribe(
  p_token text,
  p_endpoint text,
  p_p256dh text,
  p_auth text,
  p_user_agent text default ''
)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  me uuid := public.jl_player_id(p_token);
  v_id uuid;
begin
  if p_endpoint is null or length(p_endpoint) not between 20 and 2048 or p_endpoint !~ '^https://' then
    raise exception 'Subscrição push inválida.';
  end if;
  if p_p256dh is null or length(p_p256dh)<20 or p_auth is null or length(p_auth)<8 then
    raise exception 'Chaves push inválidas.';
  end if;

  insert into public.player_push_subscriptions(
    player_id,endpoint,p256dh,auth,user_agent,updated_at,disabled_at
  )
  values(
    me,left(p_endpoint,2048),left(p_p256dh,500),left(p_auth,500),
    left(coalesce(p_user_agent,''),300),now(),null
  )
  on conflict(endpoint) do update set
    player_id=excluded.player_id,
    p256dh=excluded.p256dh,
    auth=excluded.auth,
    user_agent=excluded.user_agent,
    updated_at=now(),
    disabled_at=null
  returning id into v_id;

  return jsonb_build_object('ok',true,'subscription_id',v_id);
end;
$$;

