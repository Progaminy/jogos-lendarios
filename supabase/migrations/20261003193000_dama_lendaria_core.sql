-- Dama Lendária — núcleo autoritativo 8x8
-- Regras brasileiras: captura obrigatória, Lei da Maioria, pedra captura nos dois sentidos,
-- dama voadora, promoção ao terminar a sequência, repetição e empates regulamentares.

create table if not exists public.dama_rooms (
  id uuid primary key default extensions.gen_random_uuid(),
  code text not null unique,
  host_id uuid not null references public.players(id) on delete restrict,
  guest_id uuid references public.players(id) on delete restrict,
  bet_amount numeric(12,2) not null,
  turn_seconds integer not null default 120,
  host_color text not null default 'white',
  first_player_choice text not null default 'host',
  is_public boolean not null default false,
  status text not null default 'waiting',
  current_player_id uuid references public.players(id) on delete restrict,
  started_at timestamptz,
  action_deadline timestamptz,
  pot numeric(12,2) not null default 0,
  winner_player_id uuid references public.players(id) on delete restrict,
  result_reason text,
  move_seq integer not null default 0,
  board_version integer not null default 0,
  quiet_king_moves integer not null default 0,
  regulation_key text,
  regulation_moves integer not null default 0,
  regulation_limit integer not null default 0,
  draw_offer_by uuid references public.players(id) on delete restrict,
  draw_offer_created_at timestamptz,
  draw_host_reoffer_at integer not null default 0,
  draw_guest_reoffer_at integer not null default 0,
  last_move jsonb,
  commission_total numeric(12,2) not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  finished_at timestamptz,
  constraint dama_rooms_bet_check check (bet_amount>=10 and bet_amount=trunc(bet_amount)),
  constraint dama_rooms_turn_check check (turn_seconds in (120,180)),
  constraint dama_rooms_color_check check (host_color in ('white','red')),
  constraint dama_rooms_first_check check (first_player_choice in ('host','guest')),
  constraint dama_rooms_status_check check (status in ('waiting','negotiating','funding','ready','playing','finished','cancelled')),
  constraint dama_rooms_pot_check check (pot>=0)
);

create table if not exists public.dama_room_players (
  room_id uuid not null references public.dama_rooms(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete restrict,
  seat integer not null,
  color text not null,
  settings_accepted boolean not null default false,
  stake_paid boolean not null default false,
  stake_amount numeric(12,2) not null default 0,
  move_count integer not null default 0,
  status text not null default 'active',
  joined_at timestamptz not null default now(),
  primary key(room_id,player_id),
  unique(room_id,seat),
  unique(room_id,color),
  constraint dama_room_players_seat_check check (seat in (1,2)),
  constraint dama_room_players_color_check check (color in ('white','red')),
  constraint dama_room_players_status_check check (status in ('active','left','finished'))
);

create table if not exists public.dama_pieces (
  id uuid primary key default extensions.gen_random_uuid(),
  room_id uuid not null references public.dama_rooms(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete restrict,
  piece_no integer not null,
  row_no integer not null,
  col_no integer not null,
  is_king boolean not null default false,
  alive boolean not null default true,
  updated_at timestamptz not null default now(),
  unique(room_id,player_id,piece_no),
  constraint dama_piece_no_check check (piece_no between 1 and 12),
  constraint dama_piece_row_check check (row_no between 0 and 7),
  constraint dama_piece_col_check check (col_no between 0 and 7),
  constraint dama_piece_dark_square_check check ((row_no+col_no)%2=1)
);
create unique index if not exists dama_piece_live_square_uidx
  on public.dama_pieces(room_id,row_no,col_no) where alive;
create index if not exists dama_piece_room_player_idx
  on public.dama_pieces(room_id,player_id) where alive;

create table if not exists public.dama_events (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.dama_rooms(id) on delete cascade,
  player_id uuid references public.players(id) on delete set null,
  event_type text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists dama_events_room_idx on public.dama_events(room_id,id desc);

create table if not exists public.dama_payouts (
  id uuid primary key default extensions.gen_random_uuid(),
  room_id uuid not null references public.dama_rooms(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete restrict,
  gross_amount numeric(12,2) not null,
  commission numeric(12,2) not null,
  net_amount numeric(12,2) not null,
  created_at timestamptz not null default now(),
  unique(room_id,player_id)
);

create table if not exists public.dama_positions (
  room_id uuid not null references public.dama_rooms(id) on delete cascade,
  position_key text not null,
  occurrences integer not null default 1,
  updated_at timestamptz not null default now(),
  primary key(room_id,position_key)
);

create table if not exists public.dama_signals (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.dama_rooms(id) on delete cascade,
  from_player_id uuid not null references public.players(id) on delete cascade,
  to_player_id uuid not null references public.players(id) on delete cascade,
  signal_type text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default now()+interval '2 minutes'
);
create index if not exists dama_signals_pull_idx on public.dama_signals(room_id,to_player_id,id);

