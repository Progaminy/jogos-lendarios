create or replace function public.jl_dama_room_code()
returns text
language plpgsql
security definer
set search_path=public,extensions
as $$
declare c text;
begin
  loop
    c:='DAMA-'||upper(substr(encode(extensions.gen_random_bytes(4),'hex'),1,6));
    exit when not exists(select 1 from public.dama_rooms where code=c);
  end loop;
  return c;
end;
$$;

